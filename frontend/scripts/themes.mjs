// Theme tooling. A theme is one file in src/themes holding one :root[data-theme='<id>'] block of role values, with
// its identity in three roles: --theme-label, --theme-scheme (light | dark) and --theme-order.
//
//   node scripts/themes.mjs sync                      rebuild internal/theme/registry_gen.go from the theme files
//   node scripts/themes.mjs new <id> "<Label>" <light|dark> [--from <theme id>]
//                                                     start a theme from the contract (Larry) or from another theme
//
// The server validates theme ids against that generated registry, so run `sync` (npm run themes) after adding,
// renaming or reordering a theme; the unit tests fail when the file is out of date.
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import postcss from 'postcss'

const SRC = fileURLToPath(new URL('../src/', import.meta.url))
const THEMES = join(SRC, 'themes')
const CONTRACT = join(SRC, 'styles/contract.css')
export const REGISTRY = fileURLToPath(new URL('../../internal/theme/registry_gen.go', import.meta.url))
const DEFAULT_ID = 'larry' // the theme the contract itself describes

const unquote = (v) => v.trim().replace(/^(['"])(.*)\1$/, '$2')

// declarations of the contract: every --role of its @theme and :root rules, in source order, with the comments
// that group them
function contract() {
  const items = []
  postcss.parse(readFileSync(CONTRACT, 'utf8')).each((node) => {
    const isTheme = node.type === 'atrule' && node.name === 'theme'
    const isRoot = node.type === 'rule' && node.selector === ':root'
    if (!isTheme && !isRoot) return
    let declLine = 0
    node.each((d) => {
      // a comment on the line of a declaration annotates that value ("was #..."); only group comments are kept
      if (d.type === 'comment' && d.source.start.line !== declLine) items.push({ comment: d.text })
      else if (d.type === 'decl' && d.prop.startsWith('--')) {
        items.push({ prop: d.prop, value: d.value.trim() })
        declLine = d.source.end.line
      }
    })
  })
  return items
}

// every theme: the contract as the default one, then one per :root[data-theme] block of src/themes/*.css
export function themes() {
  const base = new Map(
    contract()
      .filter((i) => i.prop)
      .map((i) => [i.prop, i.value]),
  )
  const list = [{ id: DEFAULT_ID, file: 'styles/contract.css', roles: base }]
  for (const file of readdirSync(THEMES)
    .filter((f) => f.endsWith('.css'))
    .sort()) {
    postcss.parse(readFileSync(join(THEMES, file), 'utf8')).walkRules(/^:root\[data-theme=/, (rule) => {
      const id = rule.selector.match(/data-theme=['"]([a-z0-9-]+)['"]/)[1]
      const roles = new Map(base)
      rule.walkDecls((d) => roles.set(d.prop, d.value.trim()))
      list.push({ id, file: `themes/${file}`, roles })
    })
  }
  return list
    .map((t) => ({
      id: t.id,
      file: t.file,
      label: unquote(t.roles.get('--theme-label') || t.id),
      scheme: unquote(t.roles.get('--theme-scheme') || 'light'),
      order: Number(t.roles.get('--theme-order') || 1000),
      roles: t.roles,
    }))
    .sort((a, b) => a.order - b.order || a.id.localeCompare(b.id))
}

// the Go source of the registry, one entry per line
export function registrySource(list = themes()) {
  const rows = list.map(
    (t) => `\t{ID: ${JSON.stringify(t.id)}, Label: ${JSON.stringify(t.label)}, Scheme: ${JSON.stringify(t.scheme)}},`,
  )
  return `// Code generated by frontend/scripts/themes.mjs from frontend/src/themes; DO NOT EDIT.
// Run \`npm run themes\` in frontend/ after adding, renaming or reordering a theme.

package theme

// registry lists the themes in display order; the first entry is the default of last resort.
var registry = []Theme{
${rows.join('\n')}
}
`
}

function sync() {
  const list = themes()
  writeFileSync(REGISTRY, registrySource(list))
  console.log(`registry: ${list.length} themes (${list.map((t) => t.id).join(', ')})`)
}

function create([id, label, scheme, ...rest]) {
  if (!/^[a-z][a-z0-9-]*$/.test(id || '') || !label || !['light', 'dark'].includes(scheme)) {
    console.error('usage: node scripts/themes.mjs new <id> "<Label>" <light|dark> [--from <theme id>]')
    process.exit(1)
  }
  const file = join(THEMES, `${id}.css`)
  const list = themes()
  if (existsSync(file) || list.some((t) => t.id === id)) {
    console.error(`theme ${id} already exists`)
    process.exit(1)
  }
  const fromId = rest[0] === '--from' ? rest[1] : DEFAULT_ID
  const from = list.find((t) => t.id === fromId)
  if (!from) {
    console.error(`unknown theme ${fromId}; known: ${list.map((t) => t.id).join(', ')}`)
    process.exit(1)
  }
  const meta = {
    '--theme-label': `'${label.replace(/'/g, "\\'")}'`,
    '--theme-scheme': scheme,
    '--theme-order': String(Math.max(...list.map((t) => t.order)) + 10),
  }
  const lines = [
    ...Object.entries(meta).map(([prop, value]) => `  ${prop}: ${value};`),
    ...contract()
      .filter((i) => !(i.prop in meta) && !/identity of this theme/.test(i.comment || ''))
      .map((i) => (i.comment ? `\n  /* ${i.comment} */` : `  ${i.prop}: ${from.roles.get(i.prop)};`)),
  ]
  const head = `/*\n * "${label}" theme. Reference: (name the look this theme follows and every value changed for contrast).\n * Started from ${fromId}. Only role values of the contract in ../styles/contract.css.\n */\n`
  writeFileSync(file, `${head}:root[data-theme='${id}'] {\n${lines.join('\n')}\n}\n`)
  console.log(`created src/themes/${id}.css from ${fromId}`)
  sync()
  console.log('next: edit the values, then `npm test` (structure, contrast) and `make build`')
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [cmd, ...args] = process.argv.slice(2)
  if (cmd === 'sync') sync()
  else if (cmd === 'new') create(args)
  else {
    console.error('usage: node scripts/themes.mjs sync | new <id> "<Label>" <light|dark> [--from <theme id>]')
    process.exit(1)
  }
}
